#include "srx_inline_hook.h"

#define CHECK_EQ(name, value) _Static_assert((name) == (value), #name " mismatch")

CHECK_EQ(SRX_INLINE_HOOK_MODE_SHARED, 0);
CHECK_EQ(SRX_INLINE_HOOK_MODE_UNIQUE, 1);
CHECK_EQ(SRX_INLINE_HOOK_MODE_MULTI, 2);
CHECK_EQ(SRX_INLINE_HOOK_HOOK_DEFAULT, 0);
CHECK_EQ(SRX_INLINE_HOOK_HOOK_WITH_SHARED_MODE, 1);
CHECK_EQ(SRX_INLINE_HOOK_HOOK_WITH_UNIQUE_MODE, 2);
CHECK_EQ(SRX_INLINE_HOOK_HOOK_WITH_MULTI_MODE, 4);
CHECK_EQ(SRX_INLINE_HOOK_HOOK_RECORD, 8);
CHECK_EQ(SRX_INLINE_HOOK_INTERCEPT_DEFAULT, 0);
CHECK_EQ(SRX_INLINE_HOOK_INTERCEPT_WITH_FPSIMD_READ_ONLY, 1);
CHECK_EQ(SRX_INLINE_HOOK_INTERCEPT_WITH_FPSIMD_WRITE_ONLY, 2);
CHECK_EQ(SRX_INLINE_HOOK_INTERCEPT_WITH_FPSIMD_READ_WRITE, 3);
CHECK_EQ(SRX_INLINE_HOOK_INTERCEPT_RECORD, 4);
CHECK_EQ(SRX_INLINE_HOOK_RECORD_ITEM_ALL, 0x7FF);
CHECK_EQ(SRX_INLINE_HOOK_RECORD_ITEM_TIMESTAMP, 1u << 0);
CHECK_EQ(SRX_INLINE_HOOK_RECORD_ITEM_CALLER_LIB_NAME, 1u << 1);
CHECK_EQ(SRX_INLINE_HOOK_RECORD_ITEM_OP, 1u << 2);
CHECK_EQ(SRX_INLINE_HOOK_RECORD_ITEM_LIB_NAME, 1u << 3);
CHECK_EQ(SRX_INLINE_HOOK_RECORD_ITEM_SYM_NAME, 1u << 4);
CHECK_EQ(SRX_INLINE_HOOK_RECORD_ITEM_SYM_ADDR, 1u << 5);
CHECK_EQ(SRX_INLINE_HOOK_RECORD_ITEM_NEW_ADDR, 1u << 6);
CHECK_EQ(SRX_INLINE_HOOK_RECORD_ITEM_BACKUP_LEN, 1u << 7);
CHECK_EQ(SRX_INLINE_HOOK_RECORD_ITEM_ERRNO, 1u << 8);
CHECK_EQ(SRX_INLINE_HOOK_RECORD_ITEM_STUB, 1u << 9);
CHECK_EQ(SRX_INLINE_HOOK_RECORD_ITEM_FLAGS, 1u << 10);

srx_inline_hook_mode_t srx_inline_hook_get_mode(void) {
  return SRX_INLINE_HOOK_MODE_UNIQUE;
}

int main(void) {
  return SRX_INLINE_HOOK_IS_UNIQUE_MODE && !SRX_INLINE_HOOK_IS_SHARED_MODE && !SRX_INLINE_HOOK_IS_MULTI_MODE ? 0 : 1;
}
